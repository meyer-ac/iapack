int main(int argc, char* argv[]) {
    try {
        cxxopts::Options options(
            argv[0],
            "Packaging utility for HP logic analyzer inverse assemblers");

        options.add_options()
            ("i,input", "Path to compiled inverse assembler", cxxopts::value<std::string>())
            ("o,output", "Path to place the packaged inverse assembler", cxxopts::value<std::string>())
            ("d,description", "Description text for the file browser of the logic analyzer", cxxopts::value<std::string>()->default_value(""))
            ("h,help", "This usage");

        auto result = options.parse(argc, argv);

        if (result.count("help")) {
            std::cout << options.help() << std::endl;
            return 0;
        }
        
        if (!result.count("input")) {
            std::cerr << "Error: --input is required\n\n";
            std::cout << options.help() << std::endl;
            return 1;
        }
        if (!result.count("output")) {
            std::cerr << "Error: --output is required\n\n";
            std::cout << options.help() << std::endl;
            return 1;
        }
        if (!result.count("description")) {
            std::cerr << "Error: --description is required\n\n";
            std::cout << options.help() << std::endl;
            return 1;
        }

        std::string in_file = result["input"].as<std::string>();
        std::string out_file = result["output"].as<std::string>();
        std::string description = result["description"].as<std::string>();
        std::transform(description.begin(), description.end(),
                       description.begin(), ::toupper);

        if (description.length() > desc_len) {
            std::cerr << "Error: Length of description must not exceed "
                      << desc_len << std::endl;
            return 1;
        }

        std::vector<std::uint8_t> buffer(header, header + sizeof(header));
        for (std::size_t i = 0; i < description.length(); i++) {
            char c = description.c_str()[i];
            if (c < 20 || c > 126) {
                std::cerr
                    << "Error: description must not contain control characters"
                    << std::endl;
                return 1;
            }
            buffer[desc_offset + i] = c;
        }

        std::ifstream input(in_file, std::ios::binary);
        if (!input) {
            std::cerr << "Error: Failed to open file \"" << in_file << "\""
                      << std::endl;
            return 1;
        }
        buffer.insert(buffer.end(), std::istreambuf_iterator<char>(input),
                      std::istreambuf_iterator<char>());

        std::ofstream output(out_file, std::ios::binary);
        if (!output) {
            std::cerr << "Error: Failed to open file \"" << out_file << "\""
                      << std::endl;
            return 1;
        }
        output.write(reinterpret_cast<const char*>(buffer.data()),
                     buffer.size());
    } catch (const cxxopts::exceptions::exception& e) {
        std::cerr << "Error parsing options: " << e.what() << std::endl;
        return 1;
    }

    return 0;
}
